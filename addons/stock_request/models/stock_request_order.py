    @api.depends("warehouse_id", "location_id", "stock_request_ids")
    def _compute_route_ids(self):
        route_obj = self.env["stock.route"]
        routes = route_obj.search(
            [("warehouse_ids", "in", self.mapped("warehouse_id").ids)]
        )
        routes_by_warehouse = {}
        for route in routes:
            for warehouse in route.warehouse_ids:
                routes_by_warehouse.setdefault(warehouse.id, self.env["stock.route"])
                routes_by_warehouse[warehouse.id] |= route
        for record in self:
            routes = route_obj
            if record.warehouse_id and routes_by_warehouse.get(record.warehouse_id.id):
                routes |= routes_by_warehouse[record.warehouse_id.id]
            parents = record.get_parents().ids
            valid_routes = []
            for route in routes:
                if any(p.location_dest_id.id in parents for p in route.rule_ids):
                    valid_routes.append(route)
            filtered_routes = self.env["stock.route"].browse(
                [route.id for route in valid_routes]
            )
            if record.stock_request_ids:
                all_routes = record.stock_request_ids.mapped("route_ids")
                common_routes = all_routes
                for line in record.stock_request_ids:
                    common_routes &= line.route_ids
                final_routes = filtered_routes | common_routes
                record.route_ids = [(6, 0, final_routes.ids)]
            else:
                record.route_ids = [(6, 0, filtered_routes.ids)]

    def get_parents(self):
        location = self.location_id
        result = location
        while location.location_id:
            location = location.location_id
            result |= location
        return result

    @api.depends("stock_request_ids")
    def _compute_route_id(self):
        for order in self:
            if order.stock_request_ids:
                first_route = order.stock_request_ids[0].route_id or False
                if any(r.route_id != first_route for r in order.stock_request_ids):
                    first_route = False
                order.route_id = first_route

    def _inverse_route_id(self):
        for order in self:
            if order.route_id:
                order.stock_request_ids.write({"route_id": order.route_id.id})

    @api.onchange("route_id")
    def _onchange_route_id(self):
        if self.route_id:
            for request in self.stock_request_ids:
                request.route_id = self.route_id

    @api.depends("stock_request_ids.allocation_ids", "generated_picking_ids")
    def _compute_picking_ids(self):
        for record in self:
            record.picking_ids = (
                record.stock_request_ids.mapped("picking_ids")
                | record.generated_picking_ids
            )
            record.picking_count = len(record.picking_ids)

    @api.depends("stock_request_ids", "generated_picking_ids.move_ids")
    def _compute_move_ids(self):
        for record in self:
            record.move_ids = (
                record.stock_request_ids.mapped("move_ids")
                | record.generated_picking_ids.mapped("move_ids")
            )

    @api.depends("stock_request_ids")
    def _compute_stock_request_count(self):
        for record in self:
            record.stock_request_count = len(record.stock_request_ids)

    @api.depends("purchase_order_ids")
    def _compute_purchase_count(self):
        for record in self:
            record.purchase_count = len(record.purchase_order_ids)

    def _compute_feature_flags(self):
        enabled = (
            self.env["ir.config_parameter"]
            .sudo()
            .get_param("stock_request.enable_purchase", "True")
            .lower()
            in ("true", "1")
        )
        for record in self:
            record.purchase_creation_enabled = enabled

    @api.depends("stock_request_ids.product_uom_qty", "stock_request_ids.estimated_unit_cost")
    def _compute_estimated_total(self):
        for record in self:
            record.estimated_total = sum(
                line.product_uom_qty * line.estimated_unit_cost
                for line in record.stock_request_ids
            )

    @api.depends(
        "approval_state",
        "current_approval_level",
        "level_1_approver_id",
        "level_2_approver_id",
        "level_3_approver_id",
    )
    def _compute_current_approver_id(self):
        level_fields = {
            1: "level_1_approver_id",
            2: "level_2_approver_id",
            3: "level_3_approver_id",
        }
        for request in self:
            field_name = level_fields.get(request.current_approval_level)
            request.current_approver_id = request[field_name] if field_name else False

    @api.depends("approval_state", "current_approver_id")
    @api.depends_context("uid")
    def _compute_can_current_user_approve(self):
        for request in self:
            request.can_current_user_approve = bool(
                request.current_approver_id == self.env.user
                and request.approval_state
                == f"waiting_level_{request.current_approval_level}"
            )

    def write(self, vals):
        if (
            PROTECTED_APPROVAL_FIELDS.intersection(vals)
            and not self.env.context.get("material_requisition_approval_internal")
        ):
            raise AccessError(_("Approval fields can only be changed by approval actions."))
        return super().write(vals)

    def _approval_write(self, values):
        return self.with_context(material_requisition_approval_internal=True).write(values)

    def _find_approval_config(self):
        self.ensure_one()
        configs = self.env["stock.request.approval.config"].search(
            [
                ("company_id", "=", self.company_id.id),
                ("active", "=", True),
                "|",
                ("requester_id", "=", self.requested_by.id),
                ("requester_id", "=", False),
            ],
            order="sequence, id",
        )
        return (
            configs.filtered(lambda config: config.requester_id == self.requested_by)[:1]
            or configs.filtered(lambda config: not config.requester_id)[:1]
        )

