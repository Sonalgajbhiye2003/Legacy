from odoo import _, api, fields, models
from odoo.exceptions import UserError, ValidationError


class MrpBomByproduct(models.Model):
    _inherit = "mrp.bom.byproduct"

    enable_downstream_manufacturing = fields.Boolean(
        string="Enable Downstream Manufacturing",
        help="Allow the generated by-product move to create one linked Manufacturing Order.",
    )
    downstream_bom_id = fields.Many2one(
        "mrp.bom",
        string="Downstream BoM",
        check_company=True,
        domain="[('type', '=', 'normal'), ('active', '=', True), '|', ('company_id', '=', False), ('company_id', '=', company_id)]",
        help="BoM that consumes this by-product as a direct component.",
    )

    variance_reason_required_above = fields.Float(
        string="Variance Reason Threshold",
        related="company_id.byproduct_variance_reason_threshold",
        readonly=True,
    )

    @api.constrains(
        "enable_downstream_manufacturing",
        "downstream_bom_id",
        "product_id",
        "company_id",
    )
    def _check_downstream_manufacturing_configuration(self):
        for byproduct in self.filtered("enable_downstream_manufacturing"):
            byproduct._get_downstream_configuration(ValidationError)

    def _get_downstream_configuration(self, error_type=UserError):
        self.ensure_one()
        downstream_bom = self.downstream_bom_id
        if not downstream_bom:
            raise error_type(
                _(
                    "Select a Downstream BoM for by-product %(product)s before creating the Manufacturing Order.",
                    product=self.product_id.display_name,
                )
            )
        if not downstream_bom.active or downstream_bom.type != "normal":
            raise error_type(
                _("The configured downstream BoM must be an active Manufacture this product BoM.")
            )
        if self.company_id and downstream_bom.company_id and self.company_id != downstream_bom.company_id:
            raise error_type(_("The by-product and downstream BoM must belong to the same company."))

        downstream_product = downstream_bom.product_id
        if not downstream_product:
            variants = downstream_bom.product_tmpl_id.product_variant_ids.filtered("active")
            if len(variants) != 1:
                raise error_type(
                    _(
                        "The downstream BoM must identify one finished-product variant. "
                        "Select a Product Variant on the BoM before creating the Manufacturing Order."
                    )
                )
            downstream_product = variants

        component_lines = downstream_bom.bom_line_ids.filtered(
            lambda line: line.product_id == self.product_id
            and not line._skip_bom_line(downstream_product)
        )
        if not component_lines:
            raise error_type(
                _(
                    "The downstream %(finished_product)s BoM does not contain %(byproduct)s as a direct component. "
                    "Update the downstream BoM configuration before creating the Manufacturing Order.",
                    finished_product=downstream_product.display_name,
                    byproduct=self.product_id.display_name,
                )
            )
        component_qty = sum(
            line.product_uom_id._compute_quantity(
                line.product_qty,
                self.product_id.uom_id,
                round=False,
            )
            for line in component_lines
        )
        if component_qty <= 0:
            raise error_type(
                _(
                    "The %(byproduct)s quantity on the downstream BoM must be greater than zero.",
                    byproduct=self.product_id.display_name,
                )
            )
        return downstream_bom, downstream_product, component_qty
